import Foundation

/// HTTP Method: GET, POST, PUT, DELETE, etc.
public enum HTTPMethod: String {
    /// Get.
    case GET
    
    /// Post.
    case POST
    
    /// Put.
    case PUT
    
    /// Patch.
    case PATCH
    
    /// Delete.
    case DELETE
}
